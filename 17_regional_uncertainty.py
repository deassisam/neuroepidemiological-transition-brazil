#!/usr/bin/env python3
"""
Reviewer-4 regional uncertainty table.

Inputs (generated by 06_article2_rates.py):
  outputs/article2/article2_standardized_rates.csv
  outputs/article2/article2_nti.csv

Outputs:
  outputs/reviewer_revision/Supplementary_Table_S8_regional_uncertainty.csv
  outputs/reviewer_revision/Supplementary_Table_S8_regional_uncertainty_pretty.csv

The script does not refit any mortality models. It extracts the already-computed
Poisson-approximation 95% confidence intervals for regional ASMRs and the
log-delta-method 95% confidence intervals for regional NTI values.
"""
from pathlib import Path
import sys
import numpy as np
import pandas as pd

RATES = Path("outputs/article2/article2_standardized_rates.csv")
NTI = Path("outputs/article2/article2_nti.csv")
OUTDIR = Path("outputs/reviewer_revision")
YEARS = [2000, 2024]
CAUSES = ["Cerebrovascular", "Dementia"]
REGION_ORDER = ["North", "Northeast", "Central-West", "Southeast", "South"]

EXPECTED = {
    "North": {"cvd0":48.32,"cvd1":44.28,"dem0":0.25,"dem1":7.07,"nti0":0.005,"nti1":0.160},
    "Northeast": {"cvd0":46.48,"cvd1":39.66,"dem0":0.47,"dem1":8.90,"nti0":0.010,"nti1":0.224},
    "Central-West": {"cvd0":66.05,"cvd1":35.51,"dem0":0.88,"dem1":11.72,"nti0":0.013,"nti1":0.330},
    "Southeast": {"cvd0":70.69,"cvd1":34.00,"dem0":2.71,"dem1":12.21,"nti0":0.038,"nti1":0.359},
    "South": {"cvd0":81.12,"cvd1":38.72,"dem0":2.45,"dem1":14.53,"nti0":0.030,"nti1":0.375},
}

def pct(v0, v1):
    return np.nan if not np.isfinite(v0) or v0 == 0 else 100.0*(v1/v0 - 1.0)

def fmt_rate(v, lo, hi):
    return f"{v:.2f} ({lo:.2f}–{hi:.2f})"

def fmt_nti(v, lo, hi):
    return f"{v:.3f} ({lo:.3f}–{hi:.3f})"

def main():
    if not RATES.exists() or not NTI.exists():
        sys.exit("Missing standardized-rate inputs. Run 06_article2_rates.py first.")
    OUTDIR.mkdir(parents=True, exist_ok=True)
    r = pd.read_csv(RATES)
    n = pd.read_csv(NTI)

    req_r = {"year","geography_level","geography","sex","cause","asmr_per_100k","asmr_lcl95","asmr_ucl95"}
    req_n = {"year","geography_level","geography","sex","nti","nti_lcl95","nti_ucl95"}
    if not req_r.issubset(r.columns): sys.exit(f"Rates file missing: {sorted(req_r-set(r.columns))}")
    if not req_n.issubset(n.columns): sys.exit(f"NTI file missing: {sorted(req_n-set(n.columns))}")

    rr = r[(r.geography_level=="Region") & (r.sex=="Both") & r.cause.isin(CAUSES) & r.year.isin(YEARS)].copy()
    nn = n[(n.geography_level=="Region") & (n.sex=="Both") & n.year.isin(YEARS)].copy()

    rows=[]
    for region in REGION_ORDER:
        d = rr[rr.geography==region]
        q = nn[nn.geography==region]
        def rg(cause, year):
            z=d[(d.cause==cause)&(d.year==year)]
            if len(z)!=1: raise RuntimeError(f"Expected one {cause} row for {region} {year}, found {len(z)}")
            x=z.iloc[0]
            return float(x.asmr_per_100k), float(x.asmr_lcl95), float(x.asmr_ucl95)
        def ng(year):
            z=q[q.year==year]
            if len(z)!=1: raise RuntimeError(f"Expected one NTI row for {region} {year}, found {len(z)}")
            x=z.iloc[0]
            return float(x.nti), float(x.nti_lcl95), float(x.nti_ucl95)
        cv0=rg("Cerebrovascular",2000); cv1=rg("Cerebrovascular",2024)
        dm0=rg("Dementia",2000); dm1=rg("Dementia",2024)
        nt0=ng(2000); nt1=ng(2024)
        exp=EXPECTED[region]
        checks=[(cv0[0],exp['cvd0']),(cv1[0],exp['cvd1']),(dm0[0],exp['dem0']),(dm1[0],exp['dem1']),(nt0[0],exp['nti0']),(nt1[0],exp['nti1'])]
        if not all(np.isclose(a,b,atol=0.006,rtol=0) for a,b in checks):
            raise AssertionError(f"{region}: endpoint values do not reproduce frozen Table 4 within rounding tolerance")
        rows.append({
            "Region":region,
            "Cerebrovascular_ASMR_2000":cv0[0],"Cerebrovascular_LCL95_2000":cv0[1],"Cerebrovascular_UCL95_2000":cv0[2],
            "Cerebrovascular_ASMR_2024":cv1[0],"Cerebrovascular_LCL95_2024":cv1[1],"Cerebrovascular_UCL95_2024":cv1[2],
            "Cerebrovascular_pct_change":pct(cv0[0],cv1[0]),
            "Dementia_ASMR_2000":dm0[0],"Dementia_LCL95_2000":dm0[1],"Dementia_UCL95_2000":dm0[2],
            "Dementia_ASMR_2024":dm1[0],"Dementia_LCL95_2024":dm1[1],"Dementia_UCL95_2024":dm1[2],
            "Dementia_pct_change":pct(dm0[0],dm1[0]),
            "NTI_2000":nt0[0],"NTI_LCL95_2000":nt0[1],"NTI_UCL95_2000":nt0[2],
            "NTI_2024":nt1[0],"NTI_LCL95_2024":nt1[1],"NTI_UCL95_2024":nt1[2],
            "NTI_fold_change":nt1[0]/nt0[0],
        })
    out=pd.DataFrame(rows)
    out.to_csv(OUTDIR/"Supplementary_Table_S8_regional_uncertainty.csv",index=False)
    pretty=pd.DataFrame({
        "Region":out.Region,
        "Cerebrovascular ASMR 2000 (95% CI)":[fmt_rate(v,l,u) for v,l,u in zip(out.Cerebrovascular_ASMR_2000,out.Cerebrovascular_LCL95_2000,out.Cerebrovascular_UCL95_2000)],
        "Cerebrovascular ASMR 2024 (95% CI)":[fmt_rate(v,l,u) for v,l,u in zip(out.Cerebrovascular_ASMR_2024,out.Cerebrovascular_LCL95_2024,out.Cerebrovascular_UCL95_2024)],
        "Cerebrovascular change, %":[f"{v:+.1f}%" for v in out.Cerebrovascular_pct_change],
        "Dementia ASMR 2000 (95% CI)":[fmt_rate(v,l,u) for v,l,u in zip(out.Dementia_ASMR_2000,out.Dementia_LCL95_2000,out.Dementia_UCL95_2000)],
        "Dementia ASMR 2024 (95% CI)":[fmt_rate(v,l,u) for v,l,u in zip(out.Dementia_ASMR_2024,out.Dementia_LCL95_2024,out.Dementia_UCL95_2024)],
        "Dementia change, %":[f"{v:+.1f}%" for v in out.Dementia_pct_change],
        "NTI 2000 (95% CI)":[fmt_nti(v,l,u) for v,l,u in zip(out.NTI_2000,out.NTI_LCL95_2000,out.NTI_UCL95_2000)],
        "NTI 2024 (95% CI)":[fmt_nti(v,l,u) for v,l,u in zip(out.NTI_2024,out.NTI_LCL95_2024,out.NTI_UCL95_2024)],
        "NTI fold change":[f"{v:.1f}×" for v in out.NTI_fold_change],
    })
    pretty.to_csv(OUTDIR/"Supplementary_Table_S8_regional_uncertainty_pretty.csv",index=False)
    print(pretty.to_string(index=False))
    print("\nSaved S8 files in", OUTDIR)

if __name__ == "__main__":
    main()